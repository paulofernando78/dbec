const createLesson = (seed: TravelLessonSeed): LessonContent => {
  const unitData = travel.units[seed.unit - 1];
  const lessonData = unitData.lessons[seed.lesson - 1];
  const steps: readonly LessonStepData[] = [
    {
      type: "get-ready",
      slug: "get-ready",
      label: "Get ready",
      slides: seed.targets.slice(0, 3).map((quote) => ({ image: "", audio: "", quote })),
    },
    {
      type: "listen",
      slug: "listen",
      label: "Listen",
      instruction: `Listen to the conversation: ${lessonData.title}.`,
      audio: "",
      dialogue: seed.dialogue.map(([speaker, line]) => [speaker, [line]] as const),
      questionInstruction: "Listen for gist. Choose the correct answer.",
      question: seed.gist,
      options: ["True", "False"],
      answer: "True",
      followUpInstruction: "Listen again and answer the questions.",
      followUp: seed.detail,
    },
    {
      type: "language-focus",
      slug: "language-focus",
      label: "Language focus",
      instruction: lessonData.description,
      items: seed.targets.map((phrase) => [
        phrase,
        `Use this expression when you need to ${lessonData.description.toLowerCase()}`,
        "Listen for sentence stress and polite intonation.",
        "Notice the fixed phrase and replace the travel detail when necessary.",
        undefined,
        translations[phrase],
      ] as const),
    },
    {
      type: "try-it",
      slug: "try-it",
      label: "Try it",
      instruction: "Put the travel expressions in the correct order.",
      items: seed.targets.map(shuffleWords),
    },
    {
      type: "use-it",
      slug: "use-it",
      label: "Use it",
      instruction: `Role-play the situation: ${lessonData.title}.`,
      prompts: [
        lessonData.description,
        "Decide who is the traveller and who is the service provider or travel partner.",
        "Use at least three target expressions, then change roles and change one problem or detail.",
      ],
      model: seed.dialogue.map(([speaker, line]) => [speaker, line] as const),
    },
    {
      type: "can-you",
      slug: "can-you",
      label: "Can you…?",
      instruction: "Check your travel communication skills.",
      checks: [
        `Can you ${lessonData.description.charAt(0).toLowerCase()}${lessonData.description.slice(1)}`,
        "Can you understand the important practical details in the dialogue?",
        "Can you make a clear, polite request in this situation?",
        "Can you respond when a travel plan changes or a problem occurs?",
      ],
    },
  ];

  return {
    level: "travel",
    unit: { number: unitData.number, title: unitData.title },
    lesson: { number: seed.lesson, title: lessonData.title },
    steps,
  };
};

export const travelLessons = Object.fromEntries(
  seeds.map((seed) => [`${seed.unit}/${seed.lesson}`, createLesson(seed)]),
) as Record<string, LessonContent>;
